-- ────────────────────────────────────────────
-- 11. alerts
-- ────────────────────────────────────────────
CREATE TABLE alerts (
    id                INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id           INT          NOT NULL,
    alert_type        VARCHAR(20)  NOT NULL,
    glucose_record_id BIGINT       NULL,
    weekly_report_id  INT          NULL,
    message           VARCHAR(100) NULL,
    latitude          NUMERIC(9,6) NULL,
    longitude         NUMERIC(9,6) NULL,
    is_read           BOOLEAN      NOT NULL DEFAULT FALSE,
    resolved_at       TIMESTAMP    NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at        TIMESTAMP    NULL,
    CONSTRAINT pk_alerts        PRIMARY KEY (id),
    CONSTRAINT fk_alert_user    FOREIGN KEY (user_id)           REFERENCES users (id),
    CONSTRAINT fk_alert_glucose FOREIGN KEY (glucose_record_id) REFERENCES glucose_records (id),
    CONSTRAINT fk_alert_report  FOREIGN KEY (weekly_report_id)  REFERENCES weekly_reports (id),
    CONSTRAINT ck_alerts_type   CHECK (alert_type IN ('HIGH','LOW','SOS','WEEKLY_REPORT'))
);
CREATE INDEX idx_alert_user_time ON alerts (user_id, created_at);

COMMENT ON COLUMN alerts.alert_type        IS 'HIGH / LOW / SOS / WEEKLY_REPORT';
COMMENT ON COLUMN alerts.glucose_record_id IS 'HIGH/LOW/SOS 트리거 측정';
COMMENT ON COLUMN alerts.weekly_report_id  IS '리포트 알림 대상';
COMMENT ON COLUMN alerts.latitude          IS 'SOS 발송 시 GPS 위도';
COMMENT ON COLUMN alerts.longitude         IS 'SOS 발송 시 GPS 경도';
COMMENT ON COLUMN alerts.resolved_at       IS '혈당 정상 복귀 / SOS 응답 / 사용자 확인';


