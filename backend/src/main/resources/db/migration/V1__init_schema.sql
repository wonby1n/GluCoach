-- =============================================================
-- V1: 통합 초기 스키마 (PostgreSQL)
-- -------------------------------------------------------------
-- 본 V1은 기존 V1~V6 마이그레이션을 모두 통합 + ERD 정합성 결정사항
-- 일괄 반영한 단일 마이그레이션입니다.
--
-- ERD.sql(backend/docs/ERD.sql)과 1:1 일치하며,
-- ddl-auto: validate 모드와 함께 동작합니다.
--
-- 적용 후 16개 테이블이 한 번에 생성됩니다.
-- =============================================================


-- ────────────────────────────────────────────
-- 1. users
-- ────────────────────────────────────────────
CREATE TABLE users (
    id              INT             NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email           VARCHAR(255)    NOT NULL,
    password        VARCHAR(60)     NULL,
    provider        VARCHAR(10)     NOT NULL DEFAULT 'email',
    name            VARCHAR(20)     NOT NULL,
    age             SMALLINT        NULL,
    gender          VARCHAR(6)      NULL,
    phone           VARCHAR(20)     NOT NULL,
    height          NUMERIC(4,1)    NULL,
    weight          NUMERIC(4,1)    NULL,
    diabetes_type   VARCHAR(10)     NULL DEFAULT 'NORMAL',
    is_medicated    BOOLEAN         NULL,
    target_low      NUMERIC(5,2)    NULL DEFAULT 70,
    target_high     NUMERIC(5,2)    NULL DEFAULT 140,
    week_start_day  SMALLINT        NOT NULL DEFAULT 1,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at      TIMESTAMP       NULL,
    CONSTRAINT pk_users       PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email)
);


-- ────────────────────────────────────────────
-- 2. foods
-- ────────────────────────────────────────────
CREATE TABLE foods (
    id                 INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    food_api_id        VARCHAR(64)  NULL,
    name               VARCHAR(100) NOT NULL,
    category           VARCHAR(50)  NULL,
    kcal               NUMERIC(6,2) NULL,
    carbs_g            NUMERIC(5,2) NULL,
    sugar_g            NUMERIC(5,2) NULL,
    protein_g          NUMERIC(5,2) NULL,
    fat_g              NUMERIC(5,2) NULL,
    fiber_g            NUMERIC(5,2) NULL,
    saturated_fat_g    NUMERIC(5,2) NULL,
    trans_fat_g        NUMERIC(5,2) NULL,
    cholesterol_mg     NUMERIC(5,2) NULL,
    sodium_mg          NUMERIC(5,2) NULL,
    serving_size       NUMERIC(5,2) NULL,
    is_customized      BOOLEAN      NOT NULL DEFAULT FALSE,
    search_count       INT          NOT NULL DEFAULT 0,
    cached_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_foods             PRIMARY KEY (id),
    CONSTRAINT uq_foods_food_api_id UNIQUE (food_api_id)
);
CREATE INDEX idx_foods_name      ON foods (name);
CREATE INDEX idx_foods_category  ON foods (category);
CREATE INDEX idx_foods_cached_at ON foods (cached_at);

COMMENT ON COLUMN foods.food_api_id    IS '식약처 식품코드 (foodCd). 사용자 커스텀 음식은 NULL';
COMMENT ON COLUMN foods.category       IS '식품 대분류명 (foodLv3Nm)';
COMMENT ON COLUMN foods.kcal           IS '에너지 (kcal/100g, enerc)';
COMMENT ON COLUMN foods.carbs_g        IS '탄수화물 (g/100g, chocdf)';
COMMENT ON COLUMN foods.sugar_g        IS '당류 (g/100g, sugar)';
COMMENT ON COLUMN foods.protein_g      IS '단백질 (g/100g, prot)';
COMMENT ON COLUMN foods.fat_g          IS '지방 (g/100g, fatce)';
COMMENT ON COLUMN foods.fiber_g        IS '식이섬유 (g/100g, fibtg)';
COMMENT ON COLUMN foods.saturated_fat_g IS '포화지방 (g/100g, fasat)';
COMMENT ON COLUMN foods.trans_fat_g    IS '트랜스지방 (g/100g, fatrn)';
COMMENT ON COLUMN foods.cholesterol_mg IS '콜레스테롤 (mg/100g, chole)';
COMMENT ON COLUMN foods.sodium_mg      IS '나트륨 (mg/100g, nat)';
COMMENT ON COLUMN foods.serving_size   IS '1회 제공량 기준치 (식약처 캐시는 100 고정, 커스텀은 입력값)';
COMMENT ON COLUMN foods.is_customized  IS '사용자가 등록한 음식인지 (음식 인식 실패 시 텍스트 입력)';
COMMENT ON COLUMN foods.search_count   IS '검색 히트 횟수 (캐시 우선순위)';
COMMENT ON COLUMN foods.cached_at      IS '식약처 API 마지막 호출 시각 (30일 TTL 기준)';


-- ────────────────────────────────────────────
-- 3. glucose_records
-- ────────────────────────────────────────────
CREATE TABLE glucose_records (
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id     INT          NOT NULL,
    value       NUMERIC(5,2) NOT NULL,
    measured_at TIMESTAMP    NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_glucose_records PRIMARY KEY (id),
    CONSTRAINT fk_glucose_user    FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_glucose_user_time ON glucose_records (user_id, measured_at);

COMMENT ON COLUMN glucose_records.value       IS '혈당값 (mg/dL)';
COMMENT ON COLUMN glucose_records.measured_at IS 'CGM 디바이스 측정 시각 (서버 tz=KST)';


-- ────────────────────────────────────────────
-- 4. meal_records
-- ────────────────────────────────────────────
CREATE TABLE meal_records (
    id                INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id           INT          NOT NULL,
    food_id           INT          NULL,
    image_origin_name VARCHAR(255) NULL,
    image_storage_key VARCHAR(255) NULL,
    is_processed      BOOLEAN      NOT NULL DEFAULT FALSE,
    memo              VARCHAR(255) NULL,
    recorded_at       TIMESTAMP    NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_meal_records PRIMARY KEY (id),
    CONSTRAINT fk_meal_user    FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_meal_food    FOREIGN KEY (food_id) REFERENCES foods (id)
);
CREATE INDEX idx_meal_user_time ON meal_records (user_id, recorded_at);

COMMENT ON COLUMN meal_records.food_id           IS '수동 입력 시 NULL';
COMMENT ON COLUMN meal_records.image_storage_key IS 'S3 등 외부 스토리지 키';
COMMENT ON COLUMN meal_records.recorded_at       IS '실제 식사 시각 (서버 tz=KST)';


-- ────────────────────────────────────────────
-- 5. meal_glucose_responses
-- ────────────────────────────────────────────
CREATE TABLE meal_glucose_responses (
    id                  INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id             INT          NOT NULL,
    meal_id             INT          NOT NULL,
    baseline_glucose_id BIGINT       NOT NULL,
    peak_glucose_id     BIGINT       NOT NULL,
    slope               NUMERIC(3,1) NOT NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_meal_glucose_responses PRIMARY KEY (id),
    CONSTRAINT uq_response_meal     UNIQUE (meal_id),
    CONSTRAINT fk_response_user     FOREIGN KEY (user_id)             REFERENCES users (id),
    CONSTRAINT fk_response_meal     FOREIGN KEY (meal_id)             REFERENCES meal_records (id),
    CONSTRAINT fk_response_baseline FOREIGN KEY (baseline_glucose_id) REFERENCES glucose_records (id),
    CONSTRAINT fk_response_peak     FOREIGN KEY (peak_glucose_id)     REFERENCES glucose_records (id)
);
CREATE INDEX idx_response_user ON meal_glucose_responses (user_id);

COMMENT ON COLUMN meal_glucose_responses.baseline_glucose_id IS '식전 혈당';
COMMENT ON COLUMN meal_glucose_responses.peak_glucose_id     IS '식후 2시간 내 최고 혈당';
COMMENT ON COLUMN meal_glucose_responses.slope               IS '상승 기울기 (mg/dL/min) — 등급 산출 기준';


-- ────────────────────────────────────────────
-- 6. glucose_predictions
-- ────────────────────────────────────────────
CREATE TABLE glucose_predictions (
    id              INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id         INT          NOT NULL,
    food_id         INT          NULL,
    food_name       VARCHAR(100) NULL,
    predicted_curve JSON         NOT NULL,
    predicted_peak  NUMERIC(5,2) NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_glucose_predictions PRIMARY KEY (id),
    CONSTRAINT fk_prediction_user     FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_prediction_food     FOREIGN KEY (food_id) REFERENCES foods (id)
);
CREATE INDEX idx_prediction_user_time ON glucose_predictions (user_id, created_at);

COMMENT ON COLUMN glucose_predictions.food_id         IS '음식 DB에 없는 데이터인 경우 NULL';
COMMENT ON COLUMN glucose_predictions.food_name       IS 'food_id 없을 때 수기 입력';
COMMENT ON COLUMN glucose_predictions.predicted_curve IS '예측 곡선 [{minuteOffset, glucoseMgdl}, ...]';
COMMENT ON COLUMN glucose_predictions.predicted_peak  IS '예측 최고 혈당 (mg/dL)';


-- ────────────────────────────────────────────
-- 7. user_food_grades
-- ────────────────────────────────────────────
CREATE TABLE user_food_grades (
    id         INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id    INT          NOT NULL,
    food_id    INT          NOT NULL,
    avg_slope  NUMERIC(3,1) NOT NULL,
    grade      CHAR(1)      NOT NULL,
    meal_count INT          NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_food_grades PRIMARY KEY (id),
    CONSTRAINT uq_user_food         UNIQUE (user_id, food_id),
    CONSTRAINT fk_grade_user        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_grade_food        FOREIGN KEY (food_id) REFERENCES foods (id),
    CONSTRAINT ck_user_food_grade   CHECK (grade IN ('S','A','B','C','D'))
);

COMMENT ON COLUMN user_food_grades.avg_slope  IS 'meal_glucose_responses.slope 평균';
COMMENT ON COLUMN user_food_grades.grade      IS 'S / A / B / C / D';
COMMENT ON COLUMN user_food_grades.meal_count IS '평균 산정에 사용된 식사 횟수';


-- ────────────────────────────────────────────
-- 8. weekly_reports
-- ────────────────────────────────────────────
CREATE TABLE weekly_reports (
    id                INT          NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id           INT          NOT NULL,
    week_start        DATE         NULL DEFAULT CURRENT_DATE,
    avg_glucose       NUMERIC(5,2) NULL,
    min_glucose       NUMERIC(5,2) NULL,
    max_glucose       NUMERIC(5,2) NULL,
    glucose_sd        NUMERIC(5,2) NULL,
    time_in_range     NUMERIC(5,2) NULL,
    time_above_range  NUMERIC(5,2) NULL,
    time_below_range  NUMERIC(5,2) NULL,
    ai_summary        TEXT         NULL,
    ai_suggest        TEXT         NULL,
    pdf_key           VARCHAR(100) NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_weekly_reports PRIMARY KEY (id),
    CONSTRAINT fk_report_user    FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_report_user_week ON weekly_reports (user_id, week_start);

COMMENT ON COLUMN weekly_reports.week_start       IS '리포트 커버 시작일';
COMMENT ON COLUMN weekly_reports.avg_glucose      IS '주간 평균 혈당 (mg/dL)';
COMMENT ON COLUMN weekly_reports.glucose_sd       IS '혈당 표준편차 (변동 폭)';
COMMENT ON COLUMN weekly_reports.time_in_range    IS '목표 범위 내 비율 TIR (%)';
COMMENT ON COLUMN weekly_reports.time_above_range IS '고혈당 비율 TAR (%)';
COMMENT ON COLUMN weekly_reports.time_below_range IS '저혈당 비율 TBR (%)';
COMMENT ON COLUMN weekly_reports.ai_summary       IS 'LLM 생성 주간 요약';
COMMENT ON COLUMN weekly_reports.ai_suggest       IS 'LLM 생성 개선 제안';
COMMENT ON COLUMN weekly_reports.pdf_key          IS 'S3 PDF 키 (예: reports/user_1/week_1.pdf)';


-- ────────────────────────────────────────────
